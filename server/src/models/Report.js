const mongoose = require('mongoose');

const reportSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'User ID is required']
    },
    latitude: {
      type: Number,
      required: [true, 'Latitude is required'],
      min: -90,
      max: 90
    },
    longitude: {
      type: Number,
      required: [true, 'Longitude is required'],
      min: -180,
      max: 180
    },
    areaId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Area',
      required: [true, 'Area ID is required']
    },
    description: {
      type: String,
      required: [true, 'Incident description is required'],
      trim: true,
      minlength: 5,
      maxlength: 1000
    },
    incidentType: {
      type: String,
      required: [true, 'Incident type is required'],
      enum: [
        'Theft',
        'Robbery',
        'Harassment',
        'Assault',
        'Suspicious Activity',
        'Other'
      ]
    },
    confidence: {
      type: Number,
      required: [true, 'ML Confidence is required'],
      min: 0,
      max: 1
    },
    timestamp: {
      type: Date,
      default: Date.now,
      immutable: true // Generated by server, immutable
    },
    status: {
      type: String,
      enum: ['pending_review', 'accepted', 'rejected', 'archived'],
      default: 'pending_review'
    },
    // Supporting evidence images (1-3 images, max 5MB, JPEG/PNG/WebP)
    evidenceImages: [
      {
        publicId: { type: String, default: '' },
        url: { type: String, required: true },
        fileName: { type: String, default: '' },
        fileSize: { type: Number, default: 0 },
        mimeType: { type: String, default: '' },
        storageType: { type: String, enum: ['cloudinary', 'local_secure'], default: 'local_secure' },
        uploadedAt: { type: Date, default: Date.now }
      }
    ],
    // Admin moderation decision details
    review: {
      reviewedBy: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        default: null
      },
      reviewedAt: {
        type: Date,
        default: null
      },
      decision: {
        type: String,
        enum: ['accepted', 'rejected', null],
        default: null
      },
      rejectionReason: {
        type: String,
        trim: true,
        default: null
      },
      reviewNotes: {
        type: String,
        trim: true,
        default: ''
      }
    },
    // Guarantees accepted impact is applied to area risk exactly once
    riskImpactApplied: {
      type: Boolean,
      default: false
    }
  },
  {
    timestamps: true,
    versionKey: false
  }
);

reportSchema.index({ areaId: 1, status: 1 });
reportSchema.index({ userId: 1, status: 1 });

module.exports = mongoose.model('Report', reportSchema);
