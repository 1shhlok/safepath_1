const mongoose = require('mongoose');

const reportSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'User ID is required']
    },
    latitude: {
      type: Number,
      required: [true, 'Latitude is required'],
      min: -90,
      max: 90
    },
    longitude: {
      type: Number,
      required: [true, 'Longitude is required'],
      min: -180,
      max: 180
    },
    areaId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Area',
      required: [true, 'Area ID is required']
    },
    description: {
      type: String,
      required: [true, 'Incident description is required'],
      trim: true,
      minlength: 5,
      maxlength: 1000
    },
    incidentType: {
      type: String,
      required: [true, 'Incident type is required'],
      enum: [
        'Theft',
        'Robbery',
        'Harassment',
        'Assault',
        'Suspicious Activity',
        'Other'
      ]
    },
    confidence: {
      type: Number,
      required: [true, 'ML Confidence is required'],
      min: 0,
      max: 1
    },
    timestamp: {
      type: Date,
      default: Date.now,
      immutable: true // Generated by server, immutable
    },
    status: {
      type: String,
      enum: ['active', 'low_confidence', 'flagged', 'archived'],
      default: 'active'
    }
  },
  {
    timestamps: false,
    versionKey: false
  }
);

module.exports = mongoose.model('Report', reportSchema);
